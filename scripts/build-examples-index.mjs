// Generates src/examples/__index.ts: a lazy map from example name to component.
// Each example is its own chunk, so a docs page only loads what it renders.
import { readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const dir = join(import.meta.dirname, "..", "src", "examples")
const names = readdirSync(dir)
  .filter((file) => file.endsWith(".tsx") && !file.startsWith("__"))
  .map((file) => file.replace(/\.tsx$/, ""))
  .sort()

const body = names
  .map((name) => `  "${name}": dynamic(() => import("./${name}")),`)
  .join("\n")

writeFileSync(
  join(dir, "__index.ts"),
  `// Generated by scripts/build-examples-index.mjs. Do not edit.
import type * as React from "react"
import dynamic from "next/dynamic"

export const examples: Record<string, React.ComponentType> = {
${body}
}

export const exampleNames = ${JSON.stringify(names, null, 2)} as const
`
)

console.log(`examples index: ${names.length} examples`)
